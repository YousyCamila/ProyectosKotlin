class Ejercicio1 {

    // Método para imprimir los valores de un Array
    fun imprimirArray() {
        // Crear un Array con 5 elementos enteros
        val numeros = arrayOf(10, 20, 30, 40, 50)

        // Iterar sobre cada elemento del Array usando un bucle for
        for (numero in numeros) {
            println(numero)
        }
    }
}